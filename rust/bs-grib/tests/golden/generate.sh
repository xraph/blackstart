#!/usr/bin/env bash
# Regenerates the reference golden files from ecCodes.
#
# ecCodes is ECMWF's own GRIB implementation — the reference this decoder is
# checked against, run out of process exactly as the project's guidance for
# external oracles requires. Install it with `brew install eccodes`.
#
# The golden is a sample rather than the whole field: 1.9 million values per
# message is not something to commit, and a strided sample over a stride
# coprime with the row width visits every part of the grid without aliasing
# onto a single column.
set -euo pipefail

cd "$(dirname "$0")"

# 7919 is prime and coprime with HRRR's 1799-wide rows, so the walk does not
# land on the same column repeatedly.
STRIDE=7919

for fixture in ../fixtures/*.grib2; do
	name=$(basename "$fixture" .grib2)

	{
		printf '# %s\n' "$name"
		printf '# generated by generate.sh from %s\n' \
			"$(grib_ls -V 2>&1 | grep -o 'ecCodes Version.*')"
		printf '# count\tmin\tmax\tavg\n'
		printf '#stats\t%s\n' "$(grib_get -p numberOfValues,min,max,avg "$fixture" | tr -s ' ' '\t')"
		printf '# index\tlat\tlon\tvalue\n'

		# -L raises coordinate precision from the default three decimals.
		# At HRRR's 3 km spacing three decimals is a fortieth of a cell, which
		# is fine in the interior and not fine at the exact corner: the first
		# grid point rounds to just outside its own grid.
		grib_get_data -L "%.6f %.6f" "$fixture" |
			tail -n +2 |
			awk -v stride="$STRIDE" '
				NR % stride == 1 { printf "%d\t%s\t%s\t%s\n", NR - 1, $1, $2, $3 }
			'
	} > "$name.golden"
done
