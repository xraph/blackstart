/**
 * Scenario runs, as the index grid lists them.
 *
 * The reproducibility verdict is a first-class field rather than a detail
 * buried in a run page, because determinism is a claim this project makes and
 * a claim nobody can check at a glance is not doing any work.
 */

import { z } from "zod";
import { quantity } from "./quantity";
import { typeId } from "./identity";
import { BitemporalRef } from "./temporal";

export const RUN_STATUSES = ["queued", "running", "complete", "failed"] as const;
export type RunStatus = (typeof RUN_STATUSES)[number];

/**
 * Whether re-running from the manifest reproduced the original output.
 *
 * `drift` is not a failure — an older solver version legitimately produces
 * different numbers. It is a statement that this row's result cannot be
 * regenerated by today's code, which is what a reviewer needs to know before
 * citing it.
 */
export const REPRO_VERDICTS = ["bit-exact", "drift", "pending"] as const;
export type ReproVerdict = (typeof REPRO_VERDICTS)[number];

/** Status glyphs encode shape as well as colour, so the grid survives CVD. */
export const RUN_STATUS_SHAPE: Record<RunStatus, "disc" | "wedge" | "triangle" | "ring"> = {
  complete: "disc",
  running: "wedge",
  failed: "triangle",
  queued: "ring",
};

export const ScenarioRun = z
  .object({
    id: typeId("run"),
    scenario: z.string().min(1),
    /**
     * Both axes, never merged. A run whose knowledge time trails its valid
     * time by months is a backtest and the grid says so in the row.
     */
    temporal: BitemporalRef.partial({ validTime: true }),
    solverVersion: z.string().min(1),
    /** Absent for pure solver validation runs, which use no model. */
    modelVersion: z.string().min(1).nullable(),
    status: z.enum(RUN_STATUSES),
    contingenciesSolved: z.number().int().nonnegative(),
    expectedUnservedEnergy: quantity("MW·h").nullable(),
    wallMs: z.number().int().nonnegative().nullable(),
    repro: z.enum(REPRO_VERDICTS),
  })
  .superRefine((run, ctx) => {
    const finished = run.status === "complete";

    if (finished && run.expectedUnservedEnergy === null) {
      ctx.addIssue({
        code: "custom",
        path: ["expectedUnservedEnergy"],
        message: "a complete run must report expected unserved energy",
      });
    }
    if (!finished && run.expectedUnservedEnergy !== null) {
      ctx.addIssue({
        code: "custom",
        path: ["expectedUnservedEnergy"],
        message: `a ${run.status} run has no result to report`,
      });
    }
    if (!finished && run.repro !== "pending") {
      ctx.addIssue({
        code: "custom",
        path: ["repro"],
        message: "reproducibility cannot be verdicted until the run completes",
      });
    }
  });
export type ScenarioRun = z.infer<typeof ScenarioRun>;

/**
 * The difference between two runs, which is what selecting a pair produces.
 *
 * `comparable` is computed rather than supplied: two runs are only worth
 * differencing if they share a valid time and a knowledge time, otherwise the
 * delta mixes a change in the scenario with a change in what was known.
 */
export interface RunComparison {
  readonly a: ScenarioRun;
  readonly b: ScenarioRun;
  readonly comparable: boolean;
  readonly deltaEue: number | null;
}

export function compareRuns(a: ScenarioRun, b: ScenarioRun): RunComparison {
  const comparable =
    a.temporal.validTime === b.temporal.validTime &&
    a.temporal.knowledgeTime === b.temporal.knowledgeTime;
  const deltaEue =
    a.expectedUnservedEnergy !== null && b.expectedUnservedEnergy !== null
      ? b.expectedUnservedEnergy.value - a.expectedUnservedEnergy.value
      : null;
  return { a, b, comparable, deltaEue };
}

/** `4m 18s`, the way the grid prints wall time. Null renders as an em dash. */
export function formatWall(ms: number | null): string {
  if (ms === null) return "—";
  const total = Math.round(ms / 1000);
  return `${Math.floor(total / 60)}m ${String(total % 60).padStart(2, "0")}s`;
}
