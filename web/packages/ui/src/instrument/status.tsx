/**
 * Status encoded as shape first, colour second.
 *
 * The palette is spent on the globe, so the runs grid cannot rely on hue to
 * carry state — and a grid that reads correctly in greyscale also reads
 * correctly for the eight percent of men with a colour vision deficiency.
 * Every glyph here is distinguishable by outline alone, and always sits beside
 * its word.
 */

import type { ReactElement } from "react";
import { RUN_STATUS_SHAPE, type ReproVerdict, type RunStatus } from "@blackstart/schema";
import { cn } from "../cn";

const STATUS_LABEL: Record<RunStatus, string> = {
  complete: "complete",
  running: "running",
  failed: "failed",
  queued: "queued",
};

export function StatusGlyph({ status }: { readonly status: RunStatus }): ReactElement {
  const shape = RUN_STATUS_SHAPE[status];
  return (
    <span className="inline-flex items-center gap-1.5">
      <i
        aria-hidden="true"
        className={cn(
          "size-[9px] shrink-0",
          shape === "disc" && "rounded-full border border-ok bg-ok",
          shape === "ring" && "rounded-full border border-fg-4",
          shape === "wedge" && "rounded-full border border-island-1",
          shape === "triangle" && "border border-alarm bg-alarm",
        )}
        style={
          shape === "wedge"
            ? { background: "conic-gradient(var(--bs-island-1) 0 62%, transparent 62%)" }
            : shape === "triangle"
              ? { clipPath: "polygon(50% 0, 100% 100%, 0 100%)", borderRadius: 0 }
              : undefined
        }
      />
      {STATUS_LABEL[status]}
    </span>
  );
}

/**
 * The reproducibility verdict.
 *
 * A first-class column rather than a detail on a run page. Determinism is a
 * claim this project makes, and a claim nobody can check at a glance is not
 * doing any work.
 */
const REPRO_TEXT: Record<ReproVerdict, { readonly label: string; readonly tone: string }> = {
  "bit-exact": { label: "✓ bit-exact", tone: "text-ok" },
  drift: { label: "⚠ drift", tone: "text-risk-3" },
  pending: { label: "— pending", tone: "text-fg-4" },
};

export function ReproBadge({ verdict }: { readonly verdict: ReproVerdict }): ReactElement {
  const r = REPRO_TEXT[verdict];
  const title =
    verdict === "bit-exact"
      ? "Re-running from the manifest reproduced byte-identical output"
      : verdict === "drift"
        ? "Re-running from the manifest produced different output — this result cannot be regenerated by current code"
        : "Not yet re-run";
  return (
    <span className={cn("text-[11px]", r.tone)} title={title}>
      {r.label}
    </span>
  );
}

/**
 * The advisory boundary, as permanent chrome.
 *
 * There is no `dismissible` prop and no `onClose`. Blackstart produces
 * forecasts and rankings and does not act on them; there is no code path that
 * writes to a SCADA, EMS or ADMS. That is an architectural boundary enforced
 * in CI, and the interface states it the way a lab instrument states NOT FOR
 * CLINICAL USE — permanently, not until someone clicks it away.
 */
export function AdvisoryChip({ className }: { readonly className?: string }): ReactElement {
  return (
    <span
      role="status"
      className={cn(
        "flex h-[22px] items-center gap-[7px] whitespace-nowrap rounded-[3px]",
        "border border-amber-line bg-amber-bg px-2.5",
        "font-mono text-[10px] tracking-[0.13em] text-amber",
        className,
      )}
    >
      <i aria-hidden="true" className="size-[5px] shrink-0 rounded-full bg-amber" />
      ADVISORY ONLY · NO CONTROL PATH
    </span>
  );
}
